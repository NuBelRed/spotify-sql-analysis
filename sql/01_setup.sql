CREATE TABLE spotify_data (
    row_id INTEGER,
    track_id VARCHAR(100),
    artists TEXT,
    album_name TEXT,
    track_name TEXT,
    popularity INTEGER,
    duration_ms INTEGER,
    explicit BOOLEAN,
    danceability DECIMAL,
    energy DECIMAL,
    key INTEGER,
    loudness DECIMAL,
    mode INTEGER,
    speechiness DECIMAL,
    acousticness DECIMAL,
    instrumentalness DECIMAL,
    liveness DECIMAL,
    valence DECIMAL,
    tempo DECIMAL,
    time_signature INTEGER,
    track_genre VARCHAR(100)
);

